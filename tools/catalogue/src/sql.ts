// SQL for one schema, in the history-table pattern of db/migrations/20261023000005_phase1_entity_spine.sql.
import type { Model, TypeNode } from "./model.ts";
import { oneLine, pgIdent, pgString, pgTable } from "./names.ts";

export const GENERATED_BANNER = (schema: string) =>
  `-- GENERATED by tools/catalogue from catalogue/${schema}/. Do not edit: change the catalogue and regenerate.
-- Needs the \`core\` spine (db/migrations/20261023000005_phase1_entity_spine.sql) to exist first.
`;

function wrapList(items: string[], indent: string, width = 96): string {
  const lines: string[] = [];
  let cur = "";
  for (const it of items) {
    const piece = cur === "" ? it : `${cur}, ${it}`;
    if (cur !== "" && indent.length + piece.length + 1 > width) {
      lines.push(`${cur},`);
      cur = it;
    } else cur = piece;
  }
  if (cur !== "") lines.push(cur);
  return lines.join(`\n${indent}`);
}

function tableSql(n: TypeNode): string {
  const lines: [string, string][] = []; // [name, rest]
  const tbl = pgTable(n.code);
  lines.push(["entity_id", "uuid not null"]);
  lines.push(["revision_id", "bigint not null"]);
  let disc = "";
  if (n.isChild) {
    lines.push(["position", "integer not null check (position >= 0)"]);
  } else if (n.discriminator === "kind") {
    disc = "kind";
    const q = pgString(n.code);
    lines.push(["kind", `text not null default ${q} check (kind = ${q})`]);
  } else {
    disc = "type_code";
    const list = wrapList(n.typeCodes.map(pgString), "        ");
    lines.push(["type_code", `text not null check (type_code in (\n        ${list}))`]);
  }
  for (const c of n.columns) {
    let rest = c.sql;
    if (c.notNull) rest += " not null";
    if (c.defaultSql !== undefined) rest += ` default ${c.defaultSql}`;
    if (c.refersToEntity) rest += " references core.entity (id) on delete cascade";
    for (const k of c.checks) rest += ` check (${k})`;
    lines.push([pgIdent(c.name), rest]);
  }
  const w = Math.max(...lines.map(([a]) => a.length));
  const body = lines.map(([a, b]) => `    ${a.padEnd(w)} ${b}`);
  const key = n.isChild ? "entity_id, revision_id, position" : "entity_id, revision_id";
  body.push(`    primary key (${key})`);
  if (!n.isChild && n.discriminator === "type_code") body.push("    unique (entity_id, revision_id, type_code)");
  if (n.isChild) {
    const parent = n.parent as TypeNode;
    body.push(`    foreign key (entity_id, revision_id)\n        references ${pgTable(parent.code)} (entity_id, revision_id) on delete cascade`);
  } else {
    const target = n.tabledBase ? pgTable(n.tabledBase.code) : "core.entity_version";
    body.push(`    foreign key (entity_id, revision_id, ${disc})\n        references ${target} (entity_id, revision_id, type_code) on delete cascade`);
  }
  return `create table ${tbl} (\n${body.join(",\n")}\n);`;
}

function fieldComment(c: { part?: string; field: { meaning: string } }): string {
  const m = oneLine(c.field.meaning);
  return c.part ? `${m} (${c.part})` : m;
}

export function generateSql(m: Model): string {
  const parts: string[] = [GENERATED_BANNER(m.schema)];
  parts.push(`create schema if not exists ${pgIdent(m.schema)};\n`);
  const tabled = m.types.filter((t) => t.hasTable);
  for (const n of tabled) {
    parts.push(`-- ${n.code}: ${n.doc.kind}${n.doc.base ? `, base ${n.doc.base}` : ""}${n.doc.parent ? `, parent ${n.doc.parent}` : ""}\n${tableSql(n)}\n`);
  }
  parts.push("-- append-only history");
  for (const n of tabled) {
    parts.push(
      `create trigger ${n.schema}_${n.table}_append_only before update or delete on ${pgTable(n.code)} for each row execute function core.forbid_history_rewrite();`,
    );
  }
  parts.push("\n-- meaning");
  for (const n of tabled) {
    parts.push(`comment on table ${pgTable(n.code)} is ${pgString(`${n.doc.name}: ${oneLine(n.doc.meaning)}`)};`);
    for (const c of n.columns) {
      parts.push(`comment on column ${pgTable(n.code)}.${pgIdent(c.name)} is ${pgString(fieldComment(c))};`);
    }
  }
  return `${parts.join("\n")}\n`;
}

