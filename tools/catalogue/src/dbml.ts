// DBML (dbdiagram.io / drawdb) for one schema.
import type { Model, TypeNode } from "./model.ts";
import { oneLine, pgIdent } from "./names.ts";

const q = (s: string) => `'${s.replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`;

function dbmlType(sql: string): string {
  return sql.replace("core.finite", "float8").replace("integer", "int");
}

export function generateDbml(m: Model): string {
  const out: string[] = [
    `// GENERATED by tools/catalogue from catalogue/${m.schema}/. Do not edit: change the catalogue and regenerate.`,
    "// Reads together with docs/design/db/bonyad-phase1.dbml (the core spine).",
    "",
  ];
  const refs: string[] = [];
  const tabled = m.types.filter((t) => t.hasTable);
  for (const n of tabled) out.push(...table(n, refs), "");
  out.push(...refs);
  return `${out.join("\n")}\n`;
}

function table(n: TypeNode, refs: string[]): string[] {
  const id = pgIdent;
  const t = `${n.schema}.${pgIdent(n.table)}`;
  const l: string[] = [`Table ${t} {`];
  l.push("  entity_id uuid [not null]", "  revision_id bigint [not null]");
  let disc = "";
  if (n.isChild) l.push("  position int [not null]");
  else if (n.discriminator === "kind") {
    disc = "kind";
    l.push(`  kind text [not null, default: ${q(n.code)}]`);
  } else {
    disc = "type_code";
    l.push(`  type_code text [not null, note: ${q(`one of: ${n.typeCodes.join(", ")}`)}]`);
  }
  for (const c of n.columns) {
    const attrs: string[] = [];
    if (c.notNull) attrs.push("not null");
    if (c.defaultSql !== undefined) attrs.push(`default: ${c.defaultSql}`);
    const f = c.field;
    const extra = [c.part ? `${oneLine(f.meaning)} (${c.part})` : oneLine(f.meaning)];
    if (f.type === "ref") extra.push(`ref to ${f.ref_to}`);
    if (f.source_ref) extra.push(`source: ${f.source_ref}`);
    attrs.push(`note: ${q(extra.join("; "))}`);
    l.push(`  ${id(c.name)} ${dbmlType(c.sql)} [${attrs.join(", ")}]`);
    if (c.refersToEntity) refs.push(`Ref: ${t}.${id(c.name)} > core.entity.id`);
  }
  l.push(`  Note: ${q(`${n.doc.name}: ${oneLine(n.doc.meaning)}`)}`);
  l.push("  indexes {");
  l.push(n.isChild ? "    (entity_id, revision_id, position) [pk]" : "    (entity_id, revision_id) [pk]");
  if (!n.isChild && n.discriminator === "type_code") l.push("    (entity_id, revision_id, type_code) [unique]");
  l.push("  }", "}");
  if (n.isChild) {
    refs.push(`Ref: ${t}.(entity_id, revision_id) > ${(n.parent as TypeNode).schema}.${pgIdent((n.parent as TypeNode).table)}.(entity_id, revision_id)`);
  } else {
    const target = n.tabledBase ? `${n.tabledBase.schema}.${pgIdent(n.tabledBase.table)}` : "core.entity_version";
    refs.push(`Ref: ${t}.(entity_id, revision_id, ${disc}) > ${target}.(entity_id, revision_id, type_code)`);
  }
  return l;
}
