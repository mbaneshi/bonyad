import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { convert } from "./convert.ts";
import { writeCatalogue } from "./emit.ts";
import { ACCESSED_ON, COMMIT, CORE_DIR, CORE_LICENCE, EXT_DIR, EXT_LICENCE, REPO, VERSION, WITHHOLD_EXTENSION_TEXT } from "./sources.ts";
import { listExtensions, loadDir, type Doc } from "./schema.ts";

function arg(name: string): string {
  const i = process.argv.indexOf(`--${name}`);
  const v = i >= 0 ? process.argv[i + 1] : undefined;
  if (!v) throw new Error("usage: bun run src/harvest.ts --src <KhronosGroup/glTF checkout> --out <catalogue/gltf>");
  return resolve(v);
}
const src = arg("src");
const out = arg("out");
const head = execFileSync("git", ["-C", src, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
if (head !== COMMIT) throw new Error(`checkout is at ${head}, pinned commit is ${COMMIT}`);

const docs: Doc[] = loadDir(src, CORE_DIR);
const exts = listExtensions(src, EXT_DIR);
for (const e of exts) docs.push(...loadDir(src, e.schemaDir, e.ext));
const noSchema = execFileSync("ls", [join(src, EXT_DIR)], { encoding: "utf8" })
  .split("\n")
  .filter((x) => x && !exts.some((e) => e.ext === x));

const { entries, gaps, refTable } = convert(docs, {
  repo: REPO,
  commit: COMMIT,
  accessedOn: ACCESSED_ON,
  coreVersion: VERSION,
  coreLicence: CORE_LICENCE,
  extLicence: EXT_LICENCE,
  withholdExtensionText: WITHHOLD_EXTENSION_TEXT,
});
writeCatalogue(out, entries);

const gl = gaps.map((g) => `- \`${g.where}\`: ${g.what}`).join("\n");
writeFileSync(
  join(out, "SOURCES.md"),
  `# Sources: schema \`gltf\` (Khronos glTF 2.0)

Generated by \`tools/harvest/gltf\` (\`bun run harvest\`). Do not edit by hand.

| Item | Value |
|---|---|
| Repository | https://github.com/${REPO} |
| Pinned commit | \`${COMMIT}\` |
| Version | ${VERSION} |
| Accessed | ${ACCESSED_ON} |
| Core schemas licence | ${CORE_LICENCE} |
| Extension schemas licence | ${EXT_LICENCE} |
| Fidelity | \`proxy\`: glTF is the open scene-exchange standard 3ds Max-class tools read and write; it is not 3ds Max's own model |

## Licence handling

- Core glTF 2.0 schemas (\`${CORE_DIR}\`) are CC-BY-4.0. The catalogue quotes or shortens their \`description\` text; attribution:
  "glTF 2.0 JSON Schema, (c) The Khronos Group Inc., CC BY 4.0, https://github.com/${REPO}". Changes: sentences were
  shortened, markup removed, and structure was mapped to the catalogue format.
- Khronos (\`KHR_\`) extension schemas are under the Khronos Specification Copyright, which does not allow reproducing
  excerpts. With \`WITHHOLD_EXTENSION_TEXT = ${WITHHOLD_EXTENSION_TEXT}\` (src/sources.ts) the extension entries carry only
  facts (names, types, defaults, ranges, enum values) and neutral wording written for this catalogue. See \`GAPS.md\`.
- \`LICENSE.adoc\` and \`COPYING.adoc\` at the pinned commit are the authority for the above.

## Files read

Core: every \`*.schema.json\` under \`${CORE_DIR}/\` (${docs.filter((d) => !d.ext).length} files).

Extensions: every \`*.schema.json\` under \`${EXT_DIR}/<extension>/schema/\` (${docs.filter((d) => d.ext).length} files in ${exts.length} extensions: ${exts.map((e) => e.ext).join(", ")}).

Extension directories without a schema folder (README only, no machine-readable schema): ${noSchema.join(", ") || "none"}.

Not read: \`extensions/2.0/Vendor\` and \`extensions/2.0/Archived\` (vendor and withdrawn extensions), glTF 1.0, the AsciiDoc specification text.

## Generated gap log (from the last run)

${gl || "- none"}

## Reference resolution table (glTF ids -> target type)

${"```"}
${refTable.join("\n")}
${"```"}
`,
);
writeFileSync(
  join(out, "GAPS.md"),
  `# Gaps: schema \`gltf\`

Generated by \`tools/harvest/gltf\`. What the catalogue does NOT cover, and why.

## Not covered by design

- Vendor (\`extensions/2.0/Vendor\`) and archived extensions, glTF 1.0, and the AsciiDoc prose of the specification.
- Khronos extensions without a machine-readable schema (README only): ${noSchema.join(", ") || "none"}.
- Free-form containers (\`extensions\`, \`extras\`, the \`glTFid\` scalar, the XMP JSON-LD packet) have no named members and are not types.
- Type-level \`oneOf\`/\`anyOf\`/\`not\` constraints are not modelled; where the schema states "exactly one of", it is in \`notes\`.
- Typed arrays whose element type the schema does not state (KHR_interactivity values) are not modelled.
- glTF refers to elements by array index; the catalogue stores each reference as a \`ref\` and names the target type only where the schema text makes it unambiguous (see the table in SOURCES.md). Unresolved ones use \`any\`.
- Child rows cannot nest (format rule 5): a nested object that owns child rows became an \`object\` row with \`owner\` and \`index\` fields.
- Khronos extension text is withheld (see SOURCES.md, licence handling): their descriptions are neutral wording, not quotations.
- Array fields keep their schema default only in the field text (format v0: arrays take no default).

## Generated gap log (from the last run)

${gl || "- none"}
`,
);
console.log(`wrote ${entries.length} entries to ${out}; ${gaps.length} gap notes`);
