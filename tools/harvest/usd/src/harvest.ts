import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { convertModules, type Gap, type ModuleInput } from "./convert.ts";
import { writeCatalogue } from "./emit.ts";
import { ACCESSED_ON, COMMIT, COMMIT_DATE, LICENCE, MODULES, REPO, VERSION } from "./sources.ts";
import { parseUsda } from "./usda.ts";

function arg(name: string): string {
  const i = process.argv.indexOf(`--${name}`);
  const v = i >= 0 ? process.argv[i + 1] : undefined;
  if (!v) throw new Error(`usage: bun run src/harvest.ts --src <OpenUSD checkout> --out <catalogue/usd>`);
  return resolve(v);
}

const src = arg("src");
const out = arg("out");
const head = execFileSync("git", ["-C", src, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
if (head !== COMMIT) throw new Error(`checkout is at ${head}, pinned commit is ${COMMIT}`);

const modules: ModuleInput[] = MODULES.map((m) => {
  const path = `pxr/usd/${m}/schema.usda`;
  return { module: m, path, layer: parseUsda(readFileSync(join(src, path), "utf8")) };
});

const { entries, gaps } = convertModules(modules, {
  repo: REPO,
  commit: COMMIT,
  version: VERSION,
  accessedOn: ACCESSED_ON,
  licence: LICENCE,
});
writeCatalogue(out, entries);

const rel = (gaps: Gap[]) => gaps.map((g) => `- \`${g.where}\`: ${g.what}`).join("\n");
writeFileSync(
  join(out, "SOURCES.md"),
  `# Sources: schema \`usd\` (OpenUSD)

Generated by \`tools/harvest/usd\` (\`bun run harvest\`). Do not edit by hand.

| Item | Value |
|---|---|
| Repository | https://github.com/${REPO} |
| Pinned commit | \`${COMMIT}\` (committed ${COMMIT_DATE}) |
| Version | ${VERSION} |
| Accessed | ${ACCESSED_ON} |
| Licence | ${LICENCE} |
| Fidelity | \`proxy\`: OpenUSD is the open scene standard 3ds Max-class tools exchange; it is not 3ds Max's own model |

Note on licence: the brief and the GitHub label say "Apache-2.0"; the repository's LICENSE.txt at the pinned commit
actually states the Tomorrow Open Source Technology License 1.0, which it describes as the Apache License 2.0 with a
different Section 6 (Trademarks). Recorded as the file states it. The catalogue contains facts (names, types, tokens)
and short paraphrased summaries of the schema documentation, no source code.

## Files read (one per module, all under \`pxr/usd/<module>/schema.usda\`)

${MODULES.map((m) => `- \`pxr/usd/${m}/schema.usda\` (https://github.com/${REPO}/blob/${COMMIT}/pxr/usd/${m}/schema.usda)`).join("\n")}

Also read for provenance only: \`LICENSE.txt\`, \`cmake/defaults/Version.cmake\`.

Not read: \`codegenTemplates/\` and \`testenv/\` copies of schema.usda (test fixtures and templates, not schemas).

## Generated gap log (from the last run)

${rel(gaps) || "- none"}
`,
);
writeFileSync(
  join(out, "GAPS.md"),
  `# Gaps: schema \`usd\`

Generated by \`tools/harvest/usd\`. What the catalogue does NOT cover, and why.

## Not covered by design

- Anything that is not a \`class\` prim in a \`pxr/usd/<module>/schema.usda\` (the GLOBAL token documentation, stage metadata, file-format specifics).
- Modules outside \`pxr/usd\` (for example \`pxr/usdImaging\`, \`pxr/imaging\`) and the \`codegenTemplates/\` and \`testenv/\` copies.
- Schema classes registered by plugins outside the OpenUSD repository (vendor schemas such as those of a DCC tool).
- Applied-API relations (which API schema may be applied to which prim type) are in \`notes\` only; format v0 has no relation for them.
- Relationships are stored as a single \`ref\` to \`any\`; USD allows several targets and the catalogue keeps one.
- Value types without a column mapping (\`opaque\` and any type not in the table in \`src/convert.ts\`).
- Quaternion component order is not stated in \`schema.usda\`; those fields are flagged \`needs_review\`.
- Array attributes of an abstract class without fields (for example \`UsdGeomPointBased.points\`) are folded into that class as flat float arrays, because child rows need a parent with a table.
- Fallbacks of array type are written in the field text, not as a default (format v0: arrays take no default).
- Fallbacks \`inf\` and \`nan\` cannot be a YAML default; they are stated in the field text.

## Generated gap log (from the last run)

${rel(gaps) || "- none"}
`,
);
console.log(`wrote ${entries.length} entries to ${out}; ${gaps.length} gap notes`);
