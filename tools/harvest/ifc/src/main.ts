// Usage: bun run src/main.ts <IFC4x3_RC4.exp> <docs/schemas dir> <out dir> <repo-commit-sha> [notes dir]
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { stringify } from "yaml";
import { parseExpress } from "./express.ts";
import { loadDocs } from "./docs.ts";
import { Mapper } from "./map.ts";
import { validateSet } from "./model.ts";

const [exp, docsDir, outDir, sha] = process.argv.slice(2);
if (!exp || !docsDir || !outDir || !sha) {
  console.error("usage: main.ts <schema.exp> <docs/schemas> <outDir> <commit-sha>");
  process.exit(2);
}
const raw = await Bun.file(exp).text();
const sha256 = new Bun.CryptoHasher("sha256").update(raw).digest("hex");
const schema = parseExpress(raw);
const docs = await loadDocs(docsDir);
const repo = "https://github.com/buildingSMART/IFC4.3.x-development";
const m = new Mapper(schema, docs, {
  schemaFile: `${repo}/blob/${sha}/reference_schemas/IFC4x3_RC4.exp`,
  docsBase: `${repo}/blob/${sha}/docs/schemas`,
  version: `${schema.name} (EXPRESS issue date 2021-07-22); repo commit ${sha.slice(0, 12)}; exp sha256 ${sha256.slice(0, 12)}`,
  accessedOn: "2026-10-23",
  licence: "buildingSMART: CC BY-ND 4.0 (repo LICENSE.md); EXPRESS header allows translation with full attribution, consent needed for changes. See SOURCES.md",
});
const entries = m.run();
const errs = validateSet(entries);
if (errs.length) {
  console.error(errs.slice(0, 40).join("\n"));
  console.error(`${errs.length} validation errors`);
  process.exit(1);
}
await mkdir(outDir, { recursive: true });
// only remove files this tool generates (keeps .gitignore, SOURCES.md, REVIEW.md)
for (const f of await readdir(outDir)) if (f.endsWith(".yaml") || f === "_stats.json") await rm(join(outDir, f));
for (const e of entries) {
  await writeFile(join(outDir, `${e.code.split(".")[1]}.yaml`), stringify(e, { lineWidth: 0 }));
}
const uniq = (a: string[]) => [...new Set(a)].sort();
const data_entities = uniq(m.gaps.undocumentedEntities);
const data_attrs = uniq(m.gaps.undocumentedAttrs);
const data_lits = uniq(m.gaps.undocumentedLiterals);
await writeFile(join(outDir, "_stats.json"), JSON.stringify({ stats: Object.fromEntries(Object.entries(m.stats).map(([k, v]) => [k, [...v]])), gaps: { attrs: uniq(m.gaps.undocumentedAttrs), literals: uniq(m.gaps.undocumentedLiterals), entities: uniq(m.gaps.undocumentedEntities) }, skipped: schema.skipped, sha256 }, null, 1));
console.log(`wrote ${entries.length} entries to ${outDir}`);

// GAPS.md is generated so its lists always match the YAML that was just produced.
const list = (xs: string[]) => (xs.length ? xs.map((x) => `\`${x}\``).join(", ") : "none");
const st = m.stats;
const gaps = `# IFC 4.3 catalogue: gaps

Generated by \`tools/harvest/ifc\` (do not edit by hand). Everything below is a known limit of this harvest, not a guess.

## Not stored on purpose
- **Inverse attributes** (INVERSE clauses) and **derived attributes** (DERIVE clauses) are not catalogue fields: they are computed from other data, and the catalogue holds authoritative data only. Each type lists the names it skipped in its \`notes\`. Derived redeclarations of inherited attributes are noted too.
- **WHERE rules, UNIQUE rules, global RULEs and FUNCTIONs** (${schema.skipped.functions} functions, ${schema.skipped.rules} rules in the schema) are validation logic, not data shape. Only a few narrow checks are mapped (\`positive\`, \`non_negative\`, \`unit_interval\`), and each is verified against the source text at harvest time. Everything else is dropped.
- **Defined TYPEs** (${schema.types.size}) are not catalogue types: they are resolved into the field type. Measure types without a catalogue measure (mass, force, time...) become \`float\`; their unit is the project's IfcUnitAssignment, so the unit is a property of the project, not of the column.

## Lossy mappings (documented in each field's \`source_ref\`)
- **SELECTs made only of value types** (${st.valueSelectAsText.size} attributes, e.g. IfcValue, IfcMeasureValue) are stored as \`text\`; which member type was chosen is not kept. List attributes of such a select become \`array of text\`.
- **SELECTs mixing entities and value types** (${st.mixedSelectAsAny.size} attributes) are stored as \`ref\` to \`any\`; the value members cannot be held in that column. Their types carry \`needs_review: true\`: ${list([...st.mixedSelectAsAny])}.
- **SELECTs of entities** become \`ref\` to the nearest common ancestor type, or \`any\` when there is none.
- **LOGICAL** attributes become nullable \`bool\` (UNKNOWN stored as NULL).
- **Lists of lists of entities** (grid): ${list([...st.nestedRefChildren])}. Child table with one \`item\` ref; the inner row grouping needs a second ordinal. \`needs_review: true\`.
- Aggregates (LIST, SET, ARRAY, BAG) of scalars are \`array\` fields; aggregates of entities, enums or lists of lists are child tables. Bounds (\`[1:?]\`) are kept in the child's notes only. Child types owned by an abstract type are rows of its concrete subtypes.
- IFC geometry (IfcCartesianPoint, IfcDirection) is kept as the source defines it (entities with an \`array of length\`), not collapsed into point3/vector3. Collapsing is a generator decision.
- Angles: IFC stores them in the project's plane-angle unit (degrees or radians). The catalogue says radians; the importer converts.
- IfcTimeStamp (seconds since 1970) maps to \`timestamp\`; the importer converts.
- \`kind\` is assigned by a rule (see README): entity = IfcProduct and IfcRepresentationItem descendants; symbol = type objects, materials, profiles, presentation styles, property set definitions and templates; object = everything else; abstract = ABSTRACT SUPERTYPE. It is a judgement, not something the schema states.

## Source limits
- The newest **EXPRESS** file that is readable in the public repository is IFC4X3_RC4 (issue date 2021-07-22). The final IFC 4.3 releases (ADD1, ADD2, 4.3.2.0) are published as EXPRESS on standards.buildingsmart.org, which returned a bot challenge (HTTP 403) to the one URL tried from this machine; no other mirror was tried, so they were not read. The development repository keeps the later model only as UML/XMI, which was not parsed. Entities, attributes or literals added or changed after RC4 are therefore missing or older (for example, the documentation says the IfcWallTypeEnum value ELEMENTEDWALL is no longer deprecated in 4.3.2.0, which the schema file cannot show).
- Descriptions (\`meaning\`) come from the development documentation at the pinned commit, which describes a later state than RC4. Where the two disagree, the EXPRESS decides the shape and the text may be newer.
- Entities in RC4 with **no documentation page** (${data_entities.length}): ${list(data_entities)}. Their \`meaning\` is a placeholder and the type is \`needs_review: true\`. Most are deprecated or removed from the later documentation.
- Attributes with **no description** in the documentation (${data_attrs.length}): the field \`meaning\` says "not described in the source documentation". Names: ${list(data_attrs)}.
- Enumeration literals with **no description** (${data_lits.length}): the literal's \`meaning\` says so. Names: ${list(data_lits)}.

## Not covered by design
- Property set templates and quantity set **content** (the standard Pset_* / Qto_* definitions) are data in \`docs/properties\`, not part of the EXPRESS schema. Only the generic structures (IfcPropertySet, IfcProperty*, IfcElementQuantity, IfcPhysicalQuantity*) are covered.
- IFC4.3 **MVD / concept templates**, the EXPRESS-G diagrams, and IFC2x3 / IFC4 / IFC4.1 / IFC4.2 schemas. Version differences are not modelled.
- The **bSDD** dictionary.
- File exchange (STEP/IFC parsing, ifcXML, IFC5/IFCX) is a later phase.
`;
const notesDir = process.argv[6];
if (notesDir) await writeFile(join(notesDir, "GAPS.md"), gaps);
